import { describe, expect, it } from 'vite-plus/test';
import { snoozePresets } from './snooze';

describe('snoozePresets', () => {
  // 2026-11-01 is a Sunday.
  it.each([
    ['2026-11-01', 'Sun', '2026-11-02', '2026-11-06', '2026-11-08'],
    ['2026-11-02', 'Mon', '2026-11-03', '2026-11-06', '2026-11-08'],
    ['2026-11-03', 'Tue', '2026-11-04', '2026-11-06', '2026-11-08'],
    ['2026-11-04', 'Wed', '2026-11-05', '2026-11-06', '2026-11-08'],
    ['2026-11-05', 'Thu', '2026-11-06', '2026-11-06', '2026-11-08'],
    ['2026-11-06', 'Fri', '2026-11-07', '2026-11-13', '2026-11-08'],
    ['2026-11-07', 'Sat', '2026-11-08', '2026-11-13', '2026-11-08'],
    ['2026-12-31', 'year end Thu', '2027-01-01', '2027-01-01', '2027-01-03'],
  ])('%s (%s)', (today, _name, tomorrow, weekend, nextWeek) => {
    expect(snoozePresets(today)).toEqual({ tomorrow, weekend, nextWeek });
  });
});
